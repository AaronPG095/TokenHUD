using System.IO;
using TokenHud.Core;

namespace TokenHud.App;

internal sealed record MonitorOptions(
    string? PinnedThreadId,
    long Budget,
    bool IncludeArchived,
    string Search,
    bool Paused);

internal sealed class HudMonitor : IAsyncDisposable
{
    private readonly SnapshotBuilder _builder;
    private readonly RollingDiagnostics _diagnostics;
    private readonly Func<MonitorOptions> _options;
    private readonly CodexPaths _paths;
    private readonly CancellationTokenSource _cancellation = new();
    private readonly SemaphoreSlim _wake = new(0, 1);
    private readonly List<FileSystemWatcher> _watchers = [];
    private Task? _loop;
    private DateTimeOffset _lastRefreshAt = DateTimeOffset.MinValue;
    private DateTimeOffset _lastHealthLogAt = DateTimeOffset.MinValue;

    public HudMonitor(
        SnapshotBuilder builder,
        RollingDiagnostics diagnostics,
        Func<MonitorOptions> options,
        CodexPaths paths)
    {
        _builder = builder;
        _diagnostics = diagnostics;
        _options = options;
        _paths = paths;
    }

    public event EventHandler<HudSnapshot>? SnapshotChanged;

    public void Start()
    {
        CreateWatcher(_paths.Sessions, "*.jsonl", includeSubdirectories: true);
        CreateWatcher(_paths.ArchivedSessions, "*.jsonl", includeSubdirectories: true);
        CreateWatcher(_paths.Home, "state_*.sqlite*", includeSubdirectories: false);
        _loop = RunAsync(_cancellation.Token);
    }

    public void RequestRefresh()
    {
        try
        {
            _wake.Release();
        }
        catch (SemaphoreFullException)
        {
            // A refresh is already queued.
        }
    }

    public async ValueTask DisposeAsync()
    {
        _cancellation.Cancel();
        RequestRefresh();
        if (_loop is not null)
        {
            try
            {
                await _loop.ConfigureAwait(false);
            }
            catch (OperationCanceledException)
            {
            }
        }

        foreach (var watcher in _watchers)
        {
            watcher.Dispose();
        }

        _wake.Dispose();
        _cancellation.Dispose();
    }

    private async Task RunAsync(CancellationToken cancellationToken)
    {
        while (!cancellationToken.IsCancellationRequested)
        {
            var options = _options();
            if (!options.Paused)
            {
                try
                {
                    var sinceRefresh = DateTimeOffset.UtcNow - _lastRefreshAt;
                    if (sinceRefresh < TimeSpan.FromMilliseconds(1500))
                    {
                        await Task.Delay(TimeSpan.FromMilliseconds(1500) - sinceRefresh, cancellationToken).ConfigureAwait(false);
                    }

                    var budget = Math.Clamp(options.Budget, 10_000, 1_000_000);
                    var snapshot = await _builder.BuildAsync(
                        options.PinnedThreadId,
                        new BudgetPolicy(budget),
                        options.IncludeArchived,
                        options.Search,
                        cancellationToken).ConfigureAwait(false);
                    _lastRefreshAt = DateTimeOffset.UtcNow;
                    SnapshotChanged?.Invoke(this, snapshot);
                    if (_lastRefreshAt - _lastHealthLogAt >= TimeSpan.FromMinutes(5))
                    {
                        await _diagnostics.WriteAsync(
                            "refresh_ok",
                            counters: new Dictionary<string, long>
                            {
                                ["parsed_rollouts"] = snapshot.ParsedRolloutCount,
                                ["recent_chats"] = snapshot.RecentChats.Count,
                            },
                            cancellationToken: cancellationToken).ConfigureAwait(false);
                        _lastHealthLogAt = _lastRefreshAt;
                    }
                }
                catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
                {
                    break;
                }
                catch (Exception)
                {
                    await _diagnostics.WriteAsync("refresh_failed", DiagnosticLevel.Error, cancellationToken: cancellationToken).ConfigureAwait(false);
                }
            }

            while (_wake.Wait(0))
            {
                // Coalesce file events generated by the same Codex write.
            }

            _ = await _wake.WaitAsync(TimeSpan.FromSeconds(15), cancellationToken).ConfigureAwait(false);
        }
    }

    private void CreateWatcher(string directory, string filter, bool includeSubdirectories)
    {
        if (!Directory.Exists(directory))
        {
            return;
        }

        var watcher = new FileSystemWatcher(directory, filter)
        {
            IncludeSubdirectories = includeSubdirectories,
            NotifyFilter = NotifyFilters.FileName | NotifyFilters.LastWrite | NotifyFilters.Size,
            InternalBufferSize = 32 * 1024,
            EnableRaisingEvents = true,
        };
        watcher.Changed += OnFileChanged;
        watcher.Created += OnFileChanged;
        watcher.Renamed += OnFileChanged;
        watcher.Deleted += OnFileChanged;
        watcher.Error += OnWatcherError;
        _watchers.Add(watcher);
    }

    private void OnFileChanged(object sender, FileSystemEventArgs e) => RequestRefresh();

    private void OnWatcherError(object sender, ErrorEventArgs e)
    {
        _ = _diagnostics.WriteAsync("watcher_error", DiagnosticLevel.Warning);
        RequestRefresh();
    }
}
